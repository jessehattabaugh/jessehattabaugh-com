/** Real preview-database fixture maintenance, imported only by E2E tests. */
/** @import { D1Database } from '@cloudflare/workers-types' */

/** @param {D1Database} db @param {string} email @returns {Promise<{ id: string } | null>} */
export function pendingVerification(db, email) {
	return db.prepare('SELECT id FROM email_verifications WHERE email = ? AND consumed_at IS NULL AND expires_at > ? ORDER BY created_at DESC, rowid DESC LIMIT 1')
		.bind(email, Date.now()).first();
}

/** @param {D1Database} db @param {string} token */
export function expireVerification(db, token) {
	return db.prepare('UPDATE email_verifications SET expires_at = ? WHERE id = ?').bind(Date.now() - 1000, token).run();
}

/**
 * Exercise real transaction rollback using a constraint on one unique test
 * message. SQLite schema identifiers/trigger literals cannot bind parameters;
 * only a validated, generated UUID is allowed into this fixture DDL.
 * @param {D1Database} db @param {string} messageId @param {boolean} enabled
 */
export function failFixtureMessage(db, messageId, enabled) {
	if (!/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/.test(messageId)) { throw new Error('Fixture message must be a generated UUID.'); }
	const name = `e2e_fail_${messageId.replaceAll('-', '')}`;
	return db.prepare(enabled
		? `CREATE TRIGGER ${name} BEFORE INSERT ON messages WHEN NEW.content = '${messageId}' BEGIN SELECT RAISE(ABORT, 'E2E message constraint'); END`
		: `DROP TRIGGER IF EXISTS ${name}`).run();
}

/** Delete only the identities generated by this test, including dependent rows. */
/** @param {D1Database} db @param {string} email */
export async function deleteFixtureUser(db, email) {
	for (const sql of [
		'DELETE FROM messages WHERE sender_user_id IN (SELECT id FROM users WHERE email = ?) OR conversation_id IN (SELECT c.id FROM conversations c JOIN users u ON c.visitor_user_id = u.id WHERE u.email = ?)',
		'DELETE FROM conversations WHERE visitor_user_id IN (SELECT id FROM users WHERE email = ?)',
		'DELETE FROM push_subscriptions WHERE user_id IN (SELECT id FROM users WHERE email = ?)',
		'DELETE FROM passkeys WHERE user_id IN (SELECT id FROM users WHERE email = ?)',
		'DELETE FROM auth_challenges WHERE user_id IN (SELECT id FROM users WHERE email = ?)',
		'DELETE FROM email_verifications WHERE user_id IN (SELECT id FROM users WHERE email = ?)',
		'DELETE FROM users WHERE email = ?',
	]) {
		const args = sql.includes(' OR ') ? [email, email] : [email];
		// Delete dependent rows before their parents to satisfy foreign keys.
		// eslint-disable-next-line no-await-in-loop
		await db.prepare(sql).bind(...args).run();
	}
}
